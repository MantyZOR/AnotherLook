"""Convert four vendored Lucide SVGs into native cubic paths, at build time only."""
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'third_party/font-tools'))
from fontTools.svgLib.path import parse_path
from fontTools.pens.recordingPen import RecordingPen

output=['// Generated by scripts/prepare_glyph_paths.py. Lucide ISC / Feather MIT; see Lucide-LICENSE.txt.',
        '#include "design.h"','namespace gv {','std::span<const GlyphPathCommand> GlyphPath(Glyph glyph){','switch(glyph){']
for name,glyph in [('gamepad-2','Game'),('rocket','Rocket'),('compass','Compass'),('moon','Moon')]:
    pen=RecordingPen()
    for element in ET.parse(root/f'third_party/lucide/{name}.svg').getroot():
        attrs=element.attrib
        tag=element.tag.split('}')[-1]
        if tag=='path': d=attrs['d']
        elif tag=='line': d=f"M{attrs['x1']} {attrs['y1']} L{attrs['x2']} {attrs['y2']}"
        elif tag=='circle':
            x,y,r=map(float,(attrs['cx'],attrs['cy'],attrs['r']))
            d=f'M{x+r} {y} A{r} {r} 0 1 1 {x-r} {y} A{r} {r} 0 1 1 {x+r} {y} Z'
        else: raise ValueError(tag)
        parse_path(d,pen)
    commands=[]
    for operation,points in pen.value:
        verb={'moveTo':'M','lineTo':'L','curveTo':'C','closePath':'Z','endPath':'E'}[operation]
        numbers=[v for p in points for v in p]
        def number(value):
            text=f'{value:.6f}'.rstrip('0').rstrip('.')
            if '.' not in text:text+='.0'
            return text+'f'
        commands.append("{'"+verb+"'"+(' ,'+','.join(map(number,numbers)) if numbers else '')+'}')
    output.extend([f'case Glyph::{glyph}:{{', 'static constexpr GlyphPathCommand commands[]={', ',\n'.join(commands),'};return commands;}'])
output.extend(['default:return {};','}','}','}'])
(root/'src/glyph_paths.cpp').write_text('\n'.join(output)+'\n',encoding='utf-8')
